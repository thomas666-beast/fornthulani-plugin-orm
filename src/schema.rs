//! Schema builder and migrations (Laravel's `Schema::create` / `migrate`).
//!
//! ```ignore
//! pub fn up(db: &dyn Executor) -> OrmResult<()> {
//!     Schema::create(db, "posts", |t| {
//!         t.id();
//!         t.string("title", 200);
//!         t.text("body");
//!         t.boolean("published").default(false);
//!         t.integer("user_id").references("users", "id").on_delete_cascade();
//!         t.timestamps();
//!         t.soft_deletes();
//!         t.index(&["user_id"]);
//!     })
//! }
//! pub fn down(db: &dyn Executor) -> OrmResult<()> { Schema::drop_if_exists(db, "posts") }
//! ```

use crate::conn::{Connection, Dialect, Executor};
use crate::error::{OrmError, OrmResult};
use crate::query::quote_ident;
use crate::time::now_iso;
use crate::value::SqlValue;

/// Portable column types; each dialect picks its own spelling.
#[derive(Debug, Clone, PartialEq)]
enum ColType {
    Id,
    String(u32),
    Text,
    Integer,
    BigInteger,
    Float,
    Decimal(u8, u8),
    Boolean,
    Timestamp,
    Date,
    Json,
    Uuid,
    Binary,
}

impl ColType {
    fn sql(&self, d: Dialect) -> String {
        use ColType::*;
        match (self, d) {
            (Id, Dialect::Sqlite) => "INTEGER PRIMARY KEY AUTOINCREMENT".into(),
            (Id, Dialect::Postgres) => "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY".into(),
            (String(n), _) => format!("VARCHAR({n})"),
            (Text, _) => "TEXT".into(),
            (Integer, _) => "INTEGER".into(),
            (BigInteger, _) => "BIGINT".into(),
            (Float, Dialect::Sqlite) => "REAL".into(),
            (Float, Dialect::Postgres) => "DOUBLE PRECISION".into(),
            (Decimal(p, s), _) => format!("NUMERIC({p}, {s})"),
            (Boolean, _) => "BOOLEAN".into(),
            // SQLite has no date type: ISO-8601 text sorts and compares correctly.
            (Timestamp, Dialect::Sqlite) => "TEXT".into(),
            (Timestamp, Dialect::Postgres) => "TIMESTAMPTZ".into(),
            (Date, Dialect::Sqlite) => "TEXT".into(),
            (Date, Dialect::Postgres) => "DATE".into(),
            (Json, Dialect::Sqlite) => "TEXT".into(),
            (Json, Dialect::Postgres) => "JSONB".into(),
            (Uuid, Dialect::Sqlite) => "VARCHAR(36)".into(),
            (Uuid, Dialect::Postgres) => "UUID".into(),
            (Binary, Dialect::Sqlite) => "BLOB".into(),
            (Binary, Dialect::Postgres) => "BYTEA".into(),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum OnDelete {
    NoAction,
    Cascade,
    SetNull,
    Restrict,
}

#[derive(Debug, Clone)]
pub struct ColumnDef {
    name: String,
    ty: ColType,
    nullable: bool,
    unique: bool,
    default: Option<SqlValue>,
    default_now: bool,
    references: Option<(String, String)>,
    on_delete: OnDelete,
}

impl ColumnDef {
    fn new(name: &str, ty: ColType) -> Self {
        ColumnDef {
            name: name.to_string(),
            ty,
            nullable: false,
            unique: false,
            default: None,
            default_now: false,
            references: None,
            on_delete: OnDelete::NoAction,
        }
    }

    /// Allow NULL (columns are `NOT NULL` by default).
    pub fn nullable(&mut self) -> &mut Self {
        self.nullable = true;
        self
    }

    pub fn unique(&mut self) -> &mut Self {
        self.unique = true;
        self
    }

    pub fn default(&mut self, v: impl Into<SqlValue>) -> &mut Self {
        self.default = Some(v.into());
        self
    }

    /// `DEFAULT CURRENT_TIMESTAMP`.
    pub fn use_current(&mut self) -> &mut Self {
        self.default_now = true;
        self
    }

    /// `FOREIGN KEY (this) REFERENCES table(column)`.
    pub fn references(&mut self, table: &str, column: &str) -> &mut Self {
        self.references = Some((table.to_string(), column.to_string()));
        self
    }

    /// `references(table, "id")` (Laravel's `constrained`).
    pub fn constrained(&mut self, table: &str) -> &mut Self {
        self.references(table, "id")
    }

    pub fn on_delete_cascade(&mut self) -> &mut Self {
        self.on_delete = OnDelete::Cascade;
        self
    }

    pub fn cascade_on_delete(&mut self) -> &mut Self {
        self.on_delete_cascade()
    }

    pub fn null_on_delete(&mut self) -> &mut Self {
        self.on_delete = OnDelete::SetNull;
        self.nullable = true;
        self
    }

    pub fn restrict_on_delete(&mut self) -> &mut Self {
        self.on_delete = OnDelete::Restrict;
        self
    }

    fn on_delete_sql(&self) -> &'static str {
        match self.on_delete {
            OnDelete::NoAction => "",
            OnDelete::Cascade => " ON DELETE CASCADE",
            OnDelete::SetNull => " ON DELETE SET NULL",
            OnDelete::Restrict => " ON DELETE RESTRICT",
        }
    }

    /// `"name" TYPE [NOT NULL] [UNIQUE] [DEFAULT ..]` (+ inline REFERENCES
    /// when `inline_fk`, which `ALTER TABLE ADD COLUMN` needs).
    fn def_sql(&self, d: Dialect, inline_fk: bool) -> OrmResult<String> {
        let qn = quote_ident(&self.name)?;
        let mut s = format!("{qn} {}", self.ty.sql(d));
        if self.ty != ColType::Id {
            if !self.nullable {
                s.push_str(" NOT NULL");
            }
            if self.unique {
                s.push_str(" UNIQUE");
            }
            if self.default_now {
                s.push_str(" DEFAULT CURRENT_TIMESTAMP");
            } else if let Some(v) = &self.default {
                s.push_str(&format!(" DEFAULT {}", v.to_literal(d)));
            }
        }
        if inline_fk && let Some((rt, rc)) = &self.references {
            s.push_str(&format!(
                " REFERENCES {}({}){}",
                quote_ident(rt)?,
                quote_ident(rc)?,
                self.on_delete_sql()
            ));
        }
        Ok(s)
    }
}

#[derive(Debug, Clone)]
enum AlterOp {
    DropColumn(String),
    RenameColumn(String, String),
    DropIndex(String),
}

#[derive(Debug, Default)]
pub struct Blueprint {
    columns: Vec<ColumnDef>,
    indexes: Vec<(Vec<String>, bool)>,
    alters: Vec<AlterOp>,
}

impl Blueprint {
    fn push(&mut self, name: &str, ty: ColType) -> &mut ColumnDef {
        self.columns.push(ColumnDef::new(name, ty));
        let last = self.columns.len() - 1;
        &mut self.columns[last]
    }

    /// Auto-incrementing integer primary key `id`
    /// (`INTEGER PRIMARY KEY AUTOINCREMENT` / `BIGINT ... IDENTITY`).
    pub fn id(&mut self) -> &mut ColumnDef {
        self.push("id", ColType::Id)
    }

    pub fn string(&mut self, name: &str, len: u32) -> &mut ColumnDef {
        self.push(name, ColType::String(len))
    }
    pub fn text(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Text)
    }
    pub fn integer(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Integer)
    }
    pub fn big_integer(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::BigInteger)
    }
    /// `BIGINT` foreign key column: `t.foreign_id("user_id").constrained("users").cascade_on_delete()`.
    pub fn foreign_id(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::BigInteger)
    }
    pub fn float(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Float)
    }
    /// Exact `NUMERIC(precision, scale)` (money). PostgreSQL returns it as a
    /// JSON number when that is lossless, else as a string.
    pub fn decimal(&mut self, name: &str, precision: u8, scale: u8) -> &mut ColumnDef {
        self.push(
            name,
            ColType::Decimal(precision.clamp(1, 38), scale.min(precision)),
        )
    }
    pub fn boolean(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Boolean)
    }
    /// `TIMESTAMPTZ` on PostgreSQL, ISO-8601 text on SQLite. Both read back
    /// as `YYYY-MM-DDTHH:MM:SSZ`.
    pub fn timestamp(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Timestamp)
    }
    pub fn date(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Date)
    }
    /// `JSONB` on PostgreSQL, text on SQLite. Pair with `Cast::Json`.
    pub fn json(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Json)
    }
    pub fn uuid(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Uuid)
    }
    pub fn binary(&mut self, name: &str) -> &mut ColumnDef {
        self.push(name, ColType::Binary)
    }

    /// Nullable `created_at` and `updated_at`.
    pub fn timestamps(&mut self) {
        self.timestamp("created_at").nullable();
        self.timestamp("updated_at").nullable();
    }

    /// Nullable `deleted_at`, for models with `SOFT_DELETES`.
    pub fn soft_deletes(&mut self) {
        self.timestamp("deleted_at").nullable();
    }

    pub fn index(&mut self, cols: &[&str]) {
        self.indexes
            .push((cols.iter().map(|c| c.to_string()).collect(), false));
    }

    pub fn unique_index(&mut self, cols: &[&str]) {
        self.indexes
            .push((cols.iter().map(|c| c.to_string()).collect(), true));
    }

    /// `Schema::table` only.
    pub fn drop_column(&mut self, name: &str) {
        self.alters.push(AlterOp::DropColumn(name.to_string()));
    }

    /// `Schema::table` only.
    pub fn rename_column(&mut self, from: &str, to: &str) {
        self.alters
            .push(AlterOp::RenameColumn(from.to_string(), to.to_string()));
    }

    /// Drop the index `index(cols)` / `unique_index(cols)` created (by name).
    pub fn drop_index(&mut self, cols: &[&str]) {
        self.alters.push(AlterOp::DropIndex(cols.join("_")));
    }

    fn index_sql(&self, table: &str, d: Dialect) -> OrmResult<Vec<String>> {
        let _ = d;
        let qt = quote_ident(table)?;
        let mut out = Vec::new();
        for (cols, unique) in &self.indexes {
            let quoted = cols
                .iter()
                .map(|c| quote_ident(c))
                .collect::<OrmResult<Vec<_>>>()?;
            let idx = quote_ident(&index_name(table, &cols.join("_")))?;
            out.push(format!(
                "CREATE {}INDEX {idx} ON {qt} ({})",
                if *unique { "UNIQUE " } else { "" },
                quoted.join(", ")
            ));
        }
        Ok(out)
    }

    fn to_sql(&self, table: &str, d: Dialect) -> OrmResult<Vec<String>> {
        if self.columns.is_empty() {
            return Err(OrmError::Invalid(
                "a table needs at least one column".into(),
            ));
        }
        if !self.alters.is_empty() {
            return Err(OrmError::Invalid(
                "drop/rename belong in Schema::table".into(),
            ));
        }
        let qt = quote_ident(table)?;
        let mut defs = Vec::new();
        let mut fks = Vec::new();
        for c in &self.columns {
            defs.push(c.def_sql(d, false)?);
            if let Some((rt, rc)) = &c.references {
                fks.push(format!(
                    "FOREIGN KEY ({}) REFERENCES {}({}){}",
                    quote_ident(&c.name)?,
                    quote_ident(rt)?,
                    quote_ident(rc)?,
                    c.on_delete_sql()
                ));
            }
        }
        defs.extend(fks);
        let mut out = vec![format!("CREATE TABLE {qt} ({})", defs.join(", "))];
        out.extend(self.index_sql(table, d)?);
        Ok(out)
    }

    fn to_alter_sql(&self, table: &str, d: Dialect) -> OrmResult<Vec<String>> {
        let qt = quote_ident(table)?;
        let mut out = Vec::new();
        for c in &self.columns {
            if c.ty == ColType::Id {
                return Err(OrmError::Invalid(
                    "cannot add a primary key with Schema::table".into(),
                ));
            }
            out.push(format!(
                "ALTER TABLE {qt} ADD COLUMN {}",
                c.def_sql(d, true)?
            ));
        }
        for a in &self.alters {
            out.push(match a {
                AlterOp::DropColumn(c) => {
                    format!("ALTER TABLE {qt} DROP COLUMN {}", quote_ident(c)?)
                }
                AlterOp::RenameColumn(f, t) => format!(
                    "ALTER TABLE {qt} RENAME COLUMN {} TO {}",
                    quote_ident(f)?,
                    quote_ident(t)?
                ),
                AlterOp::DropIndex(cols) => {
                    format!(
                        "DROP INDEX IF EXISTS {}",
                        quote_ident(&index_name(table, cols))?
                    )
                }
            });
        }
        out.extend(self.index_sql(table, d)?);
        Ok(out)
    }
}

/// `idx_<table>_<cols>`, shortened (with a stable hash) to fit the
/// 63-byte identifier limit of PostgreSQL.
fn index_name(table: &str, cols: &str) -> String {
    let table = table.replace('.', "_");
    let full = format!("idx_{table}_{cols}");
    if full.len() <= 63 {
        return full;
    }
    let mut h: u32 = 2_166_136_261;
    for b in full.bytes() {
        h = (h ^ u32::from(b)).wrapping_mul(16_777_619);
    }
    format!("{}_{h:08x}", &full[..54])
}

pub struct Schema;

impl Schema {
    pub fn create(
        ex: &dyn Executor,
        table: &str,
        build: impl FnOnce(&mut Blueprint),
    ) -> OrmResult<()> {
        let mut bp = Blueprint::default();
        build(&mut bp);
        for stmt in bp.to_sql(table, ex.dialect())? {
            ex.execute_batch(&stmt)?;
        }
        Ok(())
    }

    /// Alter an existing table: add columns (`t.string(..)`), `drop_column`,
    /// `rename_column`, `index`, `drop_index`.
    pub fn table(
        ex: &dyn Executor,
        table: &str,
        build: impl FnOnce(&mut Blueprint),
    ) -> OrmResult<()> {
        let mut bp = Blueprint::default();
        build(&mut bp);
        for stmt in bp.to_alter_sql(table, ex.dialect())? {
            ex.execute_batch(&stmt)?;
        }
        Ok(())
    }

    pub fn rename(ex: &dyn Executor, from: &str, to: &str) -> OrmResult<()> {
        ex.execute_batch(&format!(
            "ALTER TABLE {} RENAME TO {}",
            quote_ident(from)?,
            quote_ident(to)?
        ))
    }

    pub fn drop(ex: &dyn Executor, table: &str) -> OrmResult<()> {
        ex.execute_batch(&format!("DROP TABLE {}", quote_ident(table)?))
    }

    pub fn drop_if_exists(ex: &dyn Executor, table: &str) -> OrmResult<()> {
        let cascade = if ex.dialect() == Dialect::Postgres {
            " CASCADE"
        } else {
            ""
        };
        ex.execute_batch(&format!(
            "DROP TABLE IF EXISTS {}{cascade}",
            quote_ident(table)?
        ))
    }

    pub fn has_table(ex: &dyn Executor, table: &str) -> OrmResult<bool> {
        quote_ident(table)?;
        let rows = match ex.dialect() {
            Dialect::Sqlite => ex.query(
                "SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?",
                &[SqlValue::Text(table.to_string())],
            )?,
            Dialect::Postgres => {
                let (schema, name) = split_schema(table);
                ex.query(
                    "SELECT 1 FROM information_schema.tables \
                     WHERE table_schema = COALESCE(?, current_schema()) AND table_name = ?",
                    &[schema, SqlValue::Text(name)],
                )?
            }
        };
        Ok(!rows.is_empty())
    }

    pub fn has_column(ex: &dyn Executor, table: &str, column: &str) -> OrmResult<bool> {
        quote_ident(table)?;
        quote_ident(column)?;
        let rows = match ex.dialect() {
            Dialect::Sqlite => ex.query(
                "SELECT 1 FROM pragma_table_info(?) WHERE name = ?",
                &[
                    SqlValue::Text(table.to_string()),
                    SqlValue::Text(column.to_string()),
                ],
            )?,
            Dialect::Postgres => {
                let (schema, name) = split_schema(table);
                ex.query(
                    "SELECT 1 FROM information_schema.columns \
                     WHERE table_schema = COALESCE(?, current_schema()) AND table_name = ? AND column_name = ?",
                    &[schema, SqlValue::Text(name), SqlValue::Text(column.to_string())],
                )?
            }
        };
        Ok(!rows.is_empty())
    }
}

fn split_schema(table: &str) -> (SqlValue, String) {
    match table.split_once('.') {
        Some((s, t)) => (SqlValue::Text(s.to_string()), t.to_string()),
        None => (SqlValue::Null, table.to_string()),
    }
}

